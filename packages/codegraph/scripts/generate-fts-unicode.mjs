#!/usr/bin/env node
// Derives SQLite FTS5's unicode61 character tables from FTS5 itself (Node's
// built-in SQLite), so CodeGraph's DuckDB search tokenizes exactly as the
// FTS5 index did: which code points are token characters (FTS5 uses its own
// Unicode 6.1 tables, not the runtime's), and how each folds (lower case, a
// diacritic removed). For each code point it indexes the probe "x<c>x":
// two tokens mean <c> separates; one token means <c> is a token character,
// and the text between the two x's is its fold.
//
//   node scripts/generate-fts-unicode.mjs   writes src/db/fts-unicode.generated.ts
import { DatabaseSync } from "node:sqlite";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const out = join(dirname(fileURLToPath(import.meta.url)), "../src/db/fts-unicode.generated.ts");
const db = new DatabaseSync(":memory:");
db.exec("CREATE VIRTUAL TABLE t USING fts5(x); CREATE VIRTUAL TABLE v USING fts5vocab(t, 'instance');");
const insert = db.prepare("INSERT INTO t(rowid, x) VALUES (?, ?)");
const MAX = 0x10ffff;
db.exec("BEGIN");
for (let cp = 0; cp <= MAX; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue; // surrogates aren't characters
  insert.run(cp + 1, `x${String.fromCodePoint(cp)}x`);
}
db.exec("COMMIT");
const tokens = new Map();
for (const { doc, term } of db.prepare("SELECT doc, term FROM v ORDER BY doc, offset").iterate()) {
  const list = tokens.get(doc) ?? [];
  list.push(term);
  tokens.set(doc, list);
}
const ranges = [];
const folds = [];
let start = -1;
for (let cp = 0; cp <= MAX + 1; cp++) {
  const list = cp <= MAX ? tokens.get(cp + 1) : undefined;
  const isToken = list !== undefined && list.length === 1;
  if (isToken && start === -1) start = cp;
  if (!isToken && start !== -1) {
    ranges.push(start, cp - 1);
    start = -1;
  }
  if (isToken) {
    const fold = list[0].slice(1, -1);
    if (fold !== String.fromCodePoint(cp)) folds.push(cp, fold);
  }
}
const lines = [
  "// Generated by scripts/generate-fts-unicode.mjs from SQLite FTS5 itself; do not edit.",
  "// FTS5's unicode61 tokenizer: its token-character ranges and its folds.",
  "",
  "/** Inclusive [start, end] code-point ranges of token characters, flattened. */",
  `export const TOKEN_RANGES: readonly number[] = ${JSON.stringify(ranges)};`,
  "",
  "/** Code point, then its fold (lower case, diacritics removed; '' when removed whole), flattened. */",
  `export const FOLDS: readonly (number | string)[] = ${JSON.stringify(folds)};`,
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`${ranges.length / 2} token ranges, ${folds.length / 2} folds -> ${out}`);
